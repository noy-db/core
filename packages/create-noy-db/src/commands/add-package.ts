/**
 * `noy-db add <package>` and `noy-db add --list [prefix]` — the landscape, one
 * verb (family#118).
 *
 * ## What it is
 *
 * The scaffolder keeps the first install to hub + one store. Everything else
 * — 60-odd `to-* in-* on-* as-* by-* at-*` packages — is reached from here,
 * the way `astro add`, `nuxt module add` and `sv add` reach their ecosystems:
 * install it, wire what can be wired, and say what you just did to your trust
 * boundary. That last sentence is the part no other framework needs and this
 * one cannot skip: `as-aws-s3` and `to-aws-s3` differ in exactly the property
 * that decides who can read your data, and the prefix is the only tell.
 *
 * ## The catalog
 *
 * `--list` reads `catalog.json`, generated by the docs repo from
 * `features.yaml` and served at the docs site root. The CLI tries the live
 * URL (a few seconds, no retries) and falls back to the snapshot it ships in
 * `templates/catalog.json`, so the list works offline and the day the site is
 * down. The trust text per prefix travels IN the catalog so the family states
 * it once; this file holds no copy of it.
 *
 * ## What `add` wires
 *
 * - any package: `pnpm add <pkg>` (npm/yarn/bun detected from the lockfile).
 * - an `in-*` Nuxt module in a Nuxt project: appended to `modules` through the
 *   same magicast path the wizard's augment mode uses — idempotent, diffed.
 * - everything else: the import line to paste, because a store, an unlock
 *   method or an export format is composed in code, where a config is the
 *   app's and not ours to rewrite.
 */
import { existsSync, readFileSync } from 'node:fs'
import { join } from 'node:path'
import { spawnSync } from 'node:child_process'
import pc from 'picocolors'
import { templateDir } from '../wizard/render.js'

export const CATALOG_URL = 'https://noy-db.lanna.ai/catalog.json'

export interface CatalogPrefix {
  readonly reads: string
  readonly layer: string
  readonly plaintext: string
  readonly trust: string
}
export interface CatalogPackage {
  readonly id: string
  readonly name: string
  readonly package: string
  readonly prefix: string
  readonly section: string
  readonly status: string
  readonly producer: string | null
  readonly useCase?: string
}
export interface Catalog {
  readonly schemaVersion: number
  readonly prefixes: Record<string, CatalogPrefix>
  readonly packages: readonly CatalogPackage[]
}

/** The shipped snapshot — always available. */
export function bundledCatalog(): Catalog {
  // templateDir resolves `<package>/templates/<name>` from the built file's location.
  return JSON.parse(readFileSync(templateDir('catalog.json'), 'utf8')) as Catalog
}

/** Live first, snapshot second. Says which one it used. */
export async function loadCatalog(opts: { offline?: boolean; timeoutMs?: number; fetchImpl?: typeof fetch } = {}): Promise<{ catalog: Catalog; source: 'live' | 'bundled' }> {
  if (!opts.offline) {
    try {
      const ctl = new AbortController()
      const t = setTimeout(() => ctl.abort(), opts.timeoutMs ?? 3000)
      const res = await (opts.fetchImpl ?? fetch)(CATALOG_URL, { signal: ctl.signal })
      clearTimeout(t)
      if (res.ok) {
        const catalog = (await res.json()) as Catalog
        if (catalog.schemaVersion === 1 && Array.isArray(catalog.packages)) return { catalog, source: 'live' }
      }
    } catch { /* fall through to the snapshot */ }
  }
  return { catalog: bundledCatalog(), source: 'bundled' }
}

/** `to-`, `to`, `@noy-db/to-` and `storage`-style words all mean the to- prefix. */
export function normalisePrefix(input: string | undefined): string | undefined {
  if (!input) return undefined
  const s = input.replace(/^@noy-db\//, '').replace(/-$/, '')
  return /^(to|in|on|as|by|at)$/.test(s) ? `${s}-` : undefined
}

export function formatList(catalog: Catalog, prefix?: string): string {
  const groups = new Map<string, CatalogPackage[]>()
  for (const p of catalog.packages) {
    if (prefix && p.prefix !== prefix) continue
    ;(groups.get(p.prefix) ?? groups.set(p.prefix, []).get(p.prefix)!).push(p)
  }
  const out: string[] = []
  for (const [pfx, pkgs] of groups) {
    const g = catalog.prefixes[pfx]
    out.push(`${pc.bold(pfx)}  ${g?.reads ?? ''}  ${pc.dim(`· plaintext: ${g?.plaintext ?? '?'}`)}`)
    for (const p of pkgs) out.push(`  ${p.package.padEnd(30)} ${p.name}${p.status !== 'stable' ? pc.dim(`  (${p.status})`) : ''}`)
    out.push('')
  }
  out.push(pc.dim(`noy-db add <package> installs one and tells you what trust boundary it crosses.`))
  return out.join('\n')
}

/** Resolve a user's spelling to a catalog row: `to-aws-s3`, `aws-s3`, `@noy-db/to-aws-s3`. */
export function findPackage(catalog: Catalog, input: string): CatalogPackage | undefined {
  const full = input.startsWith('@noy-db/') ? input : `@noy-db/${input}`
  return catalog.packages.find((p) => p.package === full)
    ?? catalog.packages.find((p) => p.package.endsWith(`-${input}`))
}

export type PackageManager = 'pnpm' | 'npm' | 'yarn' | 'bun'
/** Detect from the lockfile present in `root`; pnpm when nothing says otherwise. */
export function detectPackageManager(root: string): PackageManager {
  if (existsSync(join(root, 'bun.lockb')) || existsSync(join(root, 'bun.lock'))) return 'bun'
  if (existsSync(join(root, 'yarn.lock'))) return 'yarn'
  if (existsSync(join(root, 'package-lock.json'))) return 'npm'
  return 'pnpm'
}

/** The install command, as argv. `yarn add` and `bun add` differ from `npm install`. */
export function installArgv(pm: PackageManager, pkg: string, dev: boolean): string[] {
  switch (pm) {
    case 'npm': return ['npm', 'install', ...(dev ? ['--save-dev'] : []), pkg]
    case 'yarn': return ['yarn', 'add', ...(dev ? ['--dev'] : []), pkg]
    case 'bun': return ['bun', 'add', ...(dev ? ['--dev'] : []), pkg]
    default: return ['pnpm', 'add', ...(dev ? ['-D'] : []), pkg]
  }
}

/** What to paste after installing, by layer. Short on purpose: the README of the package is the manual. */
export function snippetFor(p: CatalogPackage): string {
  const name = p.package.replace('@noy-db/', '')
  const camel = name.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase())
  switch (p.prefix) {
    case 'to-': return `import { ${camel} } from '${p.package}'\n// createNoydb({ store: ${camel}({ /* … */ }), user, secret })  — or as a sync target: sync: [{ store: ${camel}(...), role: 'backup' }]`
    case 'as-': return `import { ${camel.replace(/^as/, 'to')} } from '${p.package}'\n// await vault.export(${camel.replace(/^as/, 'to')}(), { collections: ['…'] })   ⚠️ the output is plaintext`
    case 'on-': return `import … from '${p.package}'\n// an unlock method is enrolled per user; see the package README for enroll*/unlock* and \`noy-db doctor\` for what is enrolled`
    case 'by-': return `import … from '${p.package}'\n// a session-share transport; pair it on both peers that already hold the secret`
    case 'at-': return `import … from '${p.package}'\n// createNoydb({ secretMode: 'managed', sealingKey: <provider>(…) })   ⚠️ the host you name can decrypt the slice it unseals`
    default: return `import … from '${p.package}'`
  }
}

export interface AddOptions {
  readonly root?: string
  readonly dev?: boolean
  readonly dryRun?: boolean
  readonly offline?: boolean
  readonly fetchImpl?: typeof fetch
}

export interface AddResult {
  readonly pkg: CatalogPackage
  readonly installed: boolean
  readonly command: string[]
  readonly wired: 'nuxt-module' | null
  readonly trust: string
  readonly snippet: string
}

export async function addPackage(input: string, opts: AddOptions = {}): Promise<AddResult> {
  const root = opts.root ?? process.cwd()
  const { catalog } = await loadCatalog({ ...(opts.offline !== undefined ? { offline: opts.offline } : {}), ...(opts.fetchImpl ? { fetchImpl: opts.fetchImpl } : {}) })
  const pkg = findPackage(catalog, input)
  if (!pkg) {
    const near = catalog.packages.filter((p) => p.package.includes(input.replace(/^@noy-db\//, ''))).map((p) => p.package).slice(0, 5)
    throw new Error(`no package named "${input}" in the catalog${near.length ? ` — did you mean: ${near.join(', ')}` : ''}. \`noy-db add --list\` shows them all.`)
  }
  const pm = detectPackageManager(root)
  const command = installArgv(pm, pkg.package, opts.dev ?? false)
  let installed = false
  if (!opts.dryRun) {
    const r = spawnSync(command[0]!, command.slice(1), { cwd: root, stdio: 'inherit' })
    if (r.status !== 0) throw new Error(`${command.join(' ')} exited ${r.status ?? 'with a signal'}`)
    installed = true
  }

  // Wire a Nuxt module when there is a nuxt.config and the package is an in-* with a Nuxt module.
  let wired: AddResult['wired'] = null
  if (pkg.prefix === 'in-' && pkg.package === '@noy-db/in-nuxt') {
    const cfg = ['nuxt.config.ts', 'nuxt.config.js', 'nuxt.config.mjs'].map((n) => join(root, n)).find((p) => existsSync(p))
    if (cfg && !opts.dryRun) {
      const { augmentNuxtConfig, writeAugmentedConfig } = await import('../wizard/augment.js')
      const res = await augmentNuxtConfig({ configPath: cfg, adapter: 'browser' })
      if (res.kind === 'proposed-change') { await writeAugmentedConfig(cfg, res.newCode); wired = 'nuxt-module' }
      else if (res.kind === 'already-configured') wired = 'nuxt-module'
    }
  }
  const trust = catalog.prefixes[pkg.prefix]?.trust ?? ''
  return { pkg, installed, command, wired, trust, snippet: snippetFor(pkg) }
}

// ─── CLI ──────────────────────────────────────────────────────────────────

export async function runAddPackage(argv: readonly string[]): Promise<number> {
  const flags = new Set(argv.filter((a) => a.startsWith('--')))
  const positional = argv.filter((a) => !a.startsWith('--'))
  if (flags.has('--help') || flags.has('-h')) {
    process.stdout.write([
      'Usage: noy-db add <package> [--dev] [--dry-run] [--offline]',
      '       noy-db add --list [to|in|on|as|by|at]',
      '',
      'Installs a @noy-db package with your package manager, wires it where a config can be edited',
      '(a Nuxt module), prints the import to paste otherwise, and says what trust boundary the layer crosses.',
      `The list comes from ${CATALOG_URL}, falling back to the copy this version ships.`,
    ].join('\n') + '\n')
    return 0
  }
  if (flags.has('--list')) {
    const prefix = normalisePrefix(positional[0])
    if (positional[0] && !prefix) { process.stderr.write(`unknown prefix "${positional[0]}" — one of to in on as by at\n`); return 2 }
    const { catalog, source } = await loadCatalog({ offline: flags.has('--offline') })
    process.stdout.write(formatList(catalog, prefix) + '\n' + pc.dim(`(catalog: ${source}${source === 'bundled' ? ', ' + catalog.packages.length + ' packages' : ''})`) + '\n')
    return 0
  }
  const input = positional[0]
  if (!input) { process.stderr.write('usage: noy-db add <package>   (or `noy-db add --list`)\n'); return 2 }
  try {
    const r = await addPackage(input, { dev: flags.has('--dev'), dryRun: flags.has('--dry-run'), offline: flags.has('--offline') })
    process.stdout.write(`${r.installed ? pc.green('✔') : pc.dim('dry:')} ${r.command.join(' ')}\n`)
    if (r.wired) process.stdout.write(`${pc.green('✔')} wired into nuxt.config (${r.wired})\n`)
    process.stdout.write(`\n${pc.bold(r.pkg.prefix)} ${r.trust}\n\n${r.snippet}\n`)
    return 0
  } catch (err) {
    process.stderr.write(`${pc.red('error:')} ${(err as Error).message}\n`)
    return 1
  }
}
